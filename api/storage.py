"""Small SQL adapter for local SQLite and deployed PostgreSQL."""
from contextlib import contextmanager, closing
import os
import sqlite3
import threading
from urllib.parse import urlsplit
import psycopg
from psycopg.rows import dict_row
from psycopg.conninfo import conninfo_to_dict

INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg.IntegrityError)
class DatabaseUnavailable(RuntimeError):
    """Connection failure with no public credentials or provider details."""
_initialized = set()
_schema_lock = threading.Lock()

def production():
    return os.getenv('RESTRICTAPP_ENV') == 'production'

def validate_configuration():
    url = os.getenv('DATABASE_URL','')
    if url and urlsplit(url).scheme not in {'postgres','postgresql'}:
        raise RuntimeError('DATABASE_URL must be a PostgreSQL connection URL.')
    if production():
        if not url:
            raise RuntimeError('Production requires DATABASE_URL; local SQLite is not durable on Render Free.')
        if os.getenv('RESTRICTAPP_SECURE_COOKIES') != '1':
            raise RuntimeError('Production requires secure cookies.')
        if len(os.getenv('RESTRICTAPP_RATE_SECRET','')) < 32:
            raise RuntimeError('Production requires a random RESTRICTAPP_RATE_SECRET of at least 32 characters.')
        try:
            options = conninfo_to_dict(url)
        except psycopg.Error:
            raise RuntimeError('DATABASE_URL could not be parsed; copy the complete connection string.') from None
        if options.get('sslmode') not in {'require','verify-ca','verify-full'}:
            raise RuntimeError('Production PostgreSQL requires TLS in DATABASE_URL.')

def initialize(connection, postgres):
    identity = 'BIGINT GENERATED BY DEFAULT AS IDENTITY' if postgres else 'INTEGER'
    reference = 'BIGINT' if postgres else 'INTEGER'
    timestamp = "(CURRENT_TIMESTAMP::text)" if postgres else 'CURRENT_TIMESTAMP'
    statements = [
        f'CREATE TABLE IF NOT EXISTS users (id {identity} PRIMARY KEY, email TEXT UNIQUE NOT NULL, password TEXT NOT NULL)',
        f'CREATE TABLE IF NOT EXISTS sessions (token TEXT PRIMARY KEY, user_id {reference} REFERENCES users(id) ON DELETE CASCADE, expires DOUBLE PRECISION)',
        f"CREATE TABLE IF NOT EXISTS trips (id {identity} PRIMARY KEY, user_id {reference} REFERENCES users(id) ON DELETE CASCADE, origin TEXT, destination TEXT, created TEXT DEFAULT {timestamp}, context TEXT NOT NULL DEFAULT '{{}}', UNIQUE(user_id, origin, destination))",
        f'CREATE TABLE IF NOT EXISTS profiles (user_id {reference} PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, data TEXT NOT NULL)',
        f'CREATE TABLE IF NOT EXISTS checklist_progress (trip_id {reference} REFERENCES trips(id) ON DELETE CASCADE, task_id TEXT, done INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(trip_id, task_id))',
        'CREATE TABLE IF NOT EXISTS auth_attempts (bucket TEXT PRIMARY KEY, attempts INTEGER NOT NULL, expires DOUBLE PRECISION NOT NULL)',
        'CREATE INDEX IF NOT EXISTS sessions_expires_idx ON sessions(expires)',
        'CREATE INDEX IF NOT EXISTS auth_attempts_expires_idx ON auth_attempts(expires)',
    ]
    for statement in statements:
        connection.execute(statement)
    if postgres:
        connection.execute("ALTER TABLE trips ADD COLUMN IF NOT EXISTS context TEXT NOT NULL DEFAULT '{}'")
        connection.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS preferred_language TEXT NOT NULL DEFAULT 'en'")
    elif 'context' not in {row['name'] for row in connection.execute('PRAGMA table_info(trips)')}:
        connection.execute("ALTER TABLE trips ADD COLUMN context TEXT NOT NULL DEFAULT '{}'")
    if not postgres and 'preferred_language' not in {row['name'] for row in connection.execute('PRAGMA table_info(users)')}:
        connection.execute("ALTER TABLE users ADD COLUMN preferred_language TEXT NOT NULL DEFAULT 'en'")
    connection.commit()

class Database:
    def __init__(self, connection, postgres):
        self.connection, self.postgres = connection, postgres
    def execute(self, sql, parameters=()):
        # All application statements are constant SQL; user input is bound separately.
        return self.connection.execute(sql.replace('?', '%s') if self.postgres else sql, parameters)

@contextmanager
def database(path):
    validate_configuration()
    url = os.getenv('DATABASE_URL')
    if url:
        try:
            connection = psycopg.connect(url, row_factory=dict_row, connect_timeout=10)
        except psycopg.Error:
            raise DatabaseUnavailable('PostgreSQL connection failed; check the private connection settings.') from None
        with connection:
            with _schema_lock:
                if url not in _initialized:
                    initialize(connection, True)
                    _initialized.add(url)
            yield Database(connection, True)
    else:
        path.parent.mkdir(parents=True,exist_ok=True)
        with closing(sqlite3.connect(path,timeout=15)) as connection, connection:
            connection.row_factory = sqlite3.Row
            connection.execute('PRAGMA foreign_keys = ON')
            initialize(connection, False)
            yield Database(connection, False)
